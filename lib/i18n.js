// English seed: en + vi are both complete catalogs, so a UI key missing from
// vi (a translation gap) resolves to English instead of the raw key name.
const catalogs = new Map([
  [DEFAULT_LOCALE, { ...en }],
  ["vi", { ...en, ...vi }],
]);

// Keep the previous contract available for callers that imported it.
const reserved = en;

let activeLocale = DEFAULT_LOCALE;

export function registerStrings(locale, dict) {
  const localeName = typeof locale === "string" ? locale.trim() : "";
  if (!localeName) {
    throw new OtpVaultError("Locale name is required", { code: "LOCALE_INVALID" });
  }
  if (!dict || typeof dict !== "object" || Array.isArray(dict)) {
    throw new OtpVaultError("Strings must be a plain object keyed by translation keys", {
      code: "STRINGS_INVALID",
    });
  }
  const existing = catalogs.get(localeName) || { ...en };
  const merged = { ...existing, ...dict };
  catalogs.set(localeName, merged);
  return merged;
}

export function getLocale() {
  return activeLocale;
}

export function setLocale(locale) {
  const localeName = typeof locale === "string" ? locale.trim() : "";
  if (!localeName || !catalogs.has(localeName)) {
    throw new OtpVaultError(`Unknown locale: ${localeName || String(locale)}`, { code: "LOCALE_UNKNOWN" });
  }
  activeLocale = localeName;
  return activeLocale;
}

export function getSupportedLocales() {
  return [...catalogs.keys()];
}

// Resolves the UI locale from an app setting: "system" (or empty) follows the
// browser's preferred language when a matching catalog exists; explicit
// locale names win. Falls back to the default when nothing matches.
export function resolveLocale(setting) {
  const candidate = typeof setting === "string" ? setting.trim() : "";
  if (candidate && catalogs.has(candidate)) return candidate;
  if (candidate && candidate !== "system") return DEFAULT_LOCALE;
  if (typeof navigator === "undefined") return DEFAULT_LOCALE;
  const languages = Array.isArray(navigator.languages) ? navigator.languages : navigator.language ? [navigator.language] : [];
  for (const language of languages) {
    const lower = String(language).toLowerCase();
    if (catalogs.has(lower)) return lower;
    const base = lower.split("-")[0];
    if (catalogs.has(base)) return base;
  }
  return DEFAULT_LOCALE;
}

export function t(key, params) {
  return interpolate(resolveTemplate(key), params);
}

// Missing keys resolve visibly to the key name itself (phase plan decision);
// keys missing from a partial locale catalog fall back to English first.
function resolveTemplate(key) {
  if (typeof key !== "string" || !key) return key;
  const value = catalogs.get(activeLocale)?.[key] ?? catalogs.get(DEFAULT_LOCALE)?.[key];
  return typeof value === "string" ? value : key;
}

// Only placeholders with a provided param are replaced; missing params keep
// the literal "{name}" text so gaps stay visible in the UI.
function interpolate(template, params) {
  if (typeof template !== "string") return template;
  if (!params || typeof params !== "object") return template;
  return template.replace(PLACEHOLDER_PATTERN, (match, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

// DOM application for static markup: [data-i18n] sets textContent,
// [data-i18n-placeholder] sets the placeholder attribute, and
// [data-i18n-aria-label] sets aria-label. No-op outside a document (unit
// tests). Call again after setLocale() to re-translate static markup.
export function applyTranslations(root = typeof document !== "undefined" ? document : null) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  for (const node of root.querySelectorAll("[data-i18n]")) {
    const text = t(node.getAttribute("data-i18n"));
    if (typeof text === "string") node.textContent = text;
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    const text = t(node.getAttribute("data-i18n-placeholder"));
    if (typeof text === "string") node.setAttribute("placeholder", text);
  }
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) {
    const text = t(node.getAttribute("data-i18n-aria-label"));
    if (typeof text === "string") node.setAttribute("aria-label", text);
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    const text = t(node.getAttribute("data-i18n-title"));
    if (typeof text === "string") node.setAttribute("title", text);
  }
}

// Maps the English labels returned by lib/vault.js assessPassphraseStrength
// and its warnings onto catalog keys so the UI layer can translate them.
const STRENGTH_LABEL_KEYS = {
  "Very weak": "strength.veryWeak",
  Weak: "strength.weak",
  Fair: "strength.fair",
  Good: "strength.good",
  Strong: "strength.strong",
};

const STRENGTH_WARNING_KEYS = {
  "Enter a passphrase": "strength.enterPassphrase",
  "Avoid common words and patterns": "strength.avoidCommon",
  "Use at least 12 characters for a stronger passphrase": "strength.useTwelve",
};

export function translateStrengthAssessment(assessment) {
  return {
    ...assessment,
    label: STRENGTH_LABEL_KEYS[assessment?.label] ? t(STRENGTH_LABEL_KEYS[assessment.label]) : assessment?.label,
    warnings: (assessment?.warnings || []).map((warning) => (STRENGTH_WARNING_KEYS[warning] ? t(STRENGTH_WARNING_KEYS[warning]) : warning)),
  };
}

